"""Generate lua/b10_compile.lua (the "compile every ROM file" benchmark) from a CC:Tweaked core jar.

The ROM and BIOS are CC:T code under LicenseRef-CCPL / MPL-2.0, so they are not committed to this MIT
repository. Generate the benchmark locally instead:

    python -I gen_b10_compile.py <cc-tweaked-1.21.1-core-1.121.0.jar> lua/b10_compile.lua

(The core jar is in the Gradle cache after a dev build, or at
 https://maven.squiddev.cc/cc/tweaked/cc-tweaked-1.21.1-core/1.121.0/.)
"""
import sys
import zipfile

PREFIX = "data/computercraft/lua/"


def long_bracket(text):
    level = 0
    while ("]" + "=" * level + "]") in text:
        level += 1
    return "[" + "=" * level + "[", "]" + "=" * level + "]"


def main():
    jar, out = sys.argv[1], sys.argv[2]
    with zipfile.ZipFile(jar) as z:
        names = [n for n in z.namelist() if n.startswith(PREFIX) and n.endswith(".lua")]
        names = [PREFIX + "bios.lua"] + sorted(n for n in names if n.startswith(PREFIX + "rom/"))
        files = [(n[len(PREFIX):], z.read(n).decode("latin-1")) for n in names]
    parts = [
        "-- compile: load()/loadstring() every CC:T ROM .lua file (%d files): boot/program-start cost\n" % len(files),
        "-- GENERATED by gen_b10_compile.py from %s; contains CC:T code (CCPL / MPL-2.0). Do not commit.\n"
        % jar.replace("\\", "/").split("/")[-1],
        'local NAME = "compile"\n',
        "local REPS = COMPILE_REPS or 2\n",
        "local loadstr = loadstring or load\n",
        "local SRC = {}\n",
    ]
    for path, text in files:
        o, c = long_bracket(text)
        # A long bracket skips a newline directly after the opening bracket, so add one to keep the text exact.
        parts.append('SRC[#SRC + 1] = { "%s", %s\n%s%s }\n' % (path, o, text, c))
    parts.append(
        "local function run()\n"
        "  local n, bytes = 0, 0\n"
        "  for r = 1, REPS do\n"
        "    for i = 1, #SRC do\n"
        '      local f, err = loadstr(SRC[i][2], "@" .. SRC[i][1])\n'
        '      if not f then error(SRC[i][1] .. ": " .. tostring(err)) end\n'
        "      n = n + 1; bytes = bytes + #SRC[i][2]\n"
        "    end\n"
        "  end\n"
        '  return string.format("%.0f files %.0f bytes", n, bytes)\n'
        "end\n"
    )
    with open(out, "w", encoding="latin-1", newline="\n") as f:
        f.write("".join(parts))
    print("wrote %s: %d files" % (out, len(files)))


if __name__ == "__main__":
    main()
